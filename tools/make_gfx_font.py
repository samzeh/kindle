#!/usr/bin/env python3
"""Turns a TrueType font into an Adafruit GFX font header (GFXfont).

    python3 tools/make_gfx_font.py FreeSerif.ttf 8 FreeSerif8pt7b > reader/fonts/FreeSerif8pt7b.h

Does what Adafruit's fontconvert does, with Pillow instead of a C build:
sizes in points at 141 DPI (so "8pt" here matches the library's own
FreeSerif9pt7b, 12pt7b, ... scale), 1 bit per pixel with no anti-aliasing,
and glyph bitmaps packed bit-continuously. Needs Pillow
(python3 -m pip install pillow).

The character range is 0x20-0xFF in the reader's charset, which is
Windows-1252: ASCII below 0x7F, typographic punctuation (curly quotes, en
and em dash, ellipsis, bullet, dagger) in 0x80-0x9F, and Latin-1 from 0xA0
up. See reader/charset.h. Bytes cp1252 leaves undefined, and the handful of
invisible characters (space, no-break space, soft hyphen), become empty
glyphs that draw nothing but keep their advance.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

DPI = 141
FIRST, LAST = 0x20, 0xFF


def charset_char(code):
    """The Unicode character a reader-charset byte stands for, or None if
    cp1252 leaves that byte undefined (0x81, 0x8D, 0x8F, 0x90, 0x9D)."""
    try:
        return bytes([code]).decode("cp1252")
    except UnicodeDecodeError:
        return None


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    path, points, name = sys.argv[1], float(sys.argv[2]), sys.argv[3]
    font = ImageFont.truetype(path, round(points * DPI / 72))

    bitmap = bytearray()
    glyphs = []
    missing = []
    for code in range(FIRST, LAST + 1):
        ch = charset_char(code)
        if ch is None:
            # Undefined in cp1252: an empty glyph with no advance. Nothing in
            # the text pipeline can produce this byte.
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0, code))
            continue
        advance = round(font.getlength(ch))
        # Render without anti-aliasing on a roomy canvas, then crop to the
        # pixels actually set: that is the glyph's true box.
        pad = 2 * font.size
        canvas = Image.new("1", (advance + 2 * pad, 2 * pad), 0)
        draw = ImageDraw.Draw(canvas)
        draw.fontmode = "1"  # no anti-aliasing: the panel is black and white
        draw.text((pad, pad), ch, font=font, fill=1, anchor="ls")
        box = canvas.getbbox()
        offset = len(bitmap)
        if box:
            # Relative to the pen on the baseline. Adafruit's fontconvert puts
            # glyphs 1 px lower (yOffset = 1 - bitmap_top); match it so these
            # fonts line up with the library's own.
            x0, y0 = box[0] - pad, box[1] - pad + 1
            w, h = box[2] - box[0], box[3] - box[1]
            img = canvas.crop(box)
            bits = [img.getpixel((x, y)) for y in range(h) for x in range(w)]
            for i in range(0, len(bits), 8):
                byte = 0
                for j, b in enumerate(bits[i:i + 8]):
                    if b:
                        byte |= 0x80 >> j
                bitmap.append(byte)
        else:
            w = h = x0 = y0 = 0
            # A blank box is expected for the spaces; anything else means the
            # typeface has no glyph for that character and it would silently
            # vanish, so report it on stderr.
            if advance == 0 and code not in (0x20, 0xA0, 0xAD):
                missing.append(code)
        glyphs.append((offset, w, h, advance, x0, y0, code))

    if missing:
        print(f"{name}: no glyph for " + ", ".join(f"0x{c:02X}" for c in missing),
              file=sys.stderr)

    ascent, descent = font.getmetrics()
    y_advance = ascent + descent

    print(f"// {name}: generated by tools/make_gfx_font.py from {path.split('/')[-1]}, "
          f"{points:g}pt at {DPI} DPI.")
    print("// Covers 0x20-0xFF in the reader's charset (Windows-1252); see reader/charset.h.")
    print("// GNU FreeFont, GPLv3 with the font exception (embedding in a program is allowed).")
    print("#pragma once")
    print("#include <Adafruit_GFX.h>\n")
    print(f"const uint8_t {name}Bitmaps[] PROGMEM = {{")
    for i in range(0, len(bitmap), 12):
        print("  " + ", ".join(f"0x{b:02X}" for b in bitmap[i:i + 12]) + ",")
    print("};\n")
    print(f"const GFXglyph {name}Glyphs[] PROGMEM = {{")
    for offset, w, h, adv, xo, yo, code in glyphs:
        if code == 0x20:
            label = "' '"
        elif code < 0x7F:
            label = "'\\\\'" if chr(code) == "\\" else f"'{chr(code)}'"
        else:
            ch = charset_char(code)
            # Non-ASCII goes in the comment as U+XXXX rather than the
            # character itself, so the header stays plain ASCII.
            label = f"U+{ord(ch):04X}" if ch else "undefined"
        print(f"  {{ {offset}, {w}, {h}, {adv}, {xo}, {yo} }},  // 0x{code:02X} {label}")
    print("};\n")
    print(f"const GFXfont {name} PROGMEM = {{ (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs,")
    print(f"                                0x{FIRST:02X}, 0x{LAST:02X}, {y_advance} }};")


if __name__ == "__main__":
    main()
