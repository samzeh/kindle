static const uint32_t BUSY_TIMEOUT_MS = 10000;

// ---- Software SPI ----
// Same signal sequence as the vendor demo, but the pins are switched by
// writing the ESP32's GPIO registers directly: digitalWrite() is slow
// enough that sending one page took ~1.4 s.

static_assert(PIN_EPD_SCK < 32 && PIN_EPD_MOSI < 32 && PIN_EPD_CS < 32 && PIN_EPD_DC < 32,
              "fast pin writes below only handle GPIO 0-31");

static inline void pinHigh(uint8_t pin) {
  REG_WRITE(GPIO_OUT_W1TS_REG, 1UL << pin);
}

static inline void pinLow(uint8_t pin) {
  REG_WRITE(GPIO_OUT_W1TC_REG, 1UL << pin);
}

static void spiWrite(uint8_t value) {
  for (uint8_t i = 0; i < 8; i++) {
    pinLow(PIN_EPD_SCK);
    if (value & 0x80) pinHigh(PIN_EPD_MOSI);
    else pinLow(PIN_EPD_MOSI);
    value <<= 1;
    pinHigh(PIN_EPD_SCK);
  }
}

static void writeCommand(uint8_t command) {
  pinLow(PIN_EPD_CS);
  pinLow(PIN_EPD_DC);
  spiWrite(command);
  pinHigh(PIN_EPD_CS);
}

static void writeData(uint8_t data) {
  pinLow(PIN_EPD_CS);
  pinHigh(PIN_EPD_DC);
  spiWrite(data);
  pinHigh(PIN_EPD_CS);
}

// CS is toggled for every byte, as in the vendor demo.
static void writeImage(uint8_t ramCommand, const uint8_t *image) {
  const uint16_t rowBytes = EPD_NATIVE_WIDTH / 8;
  writeCommand(ramCommand);
  for (uint16_t r = 0; r < EPD_NATIVE_HEIGHT; r++) {
    uint16_t row = EPD_FLIP_ROWS ? EPD_NATIVE_HEIGHT - 1 - r : r;
    for (uint16_t b = 0; b < rowBytes; b++) writeData(image[row * rowBytes + b]);
  }
}

// The data line doubles as input for reads (3-wire SPI).
static uint8_t readData() {
  uint8_t value = 0;
  pinMode(PIN_EPD_MOSI, INPUT);
  digitalWrite(PIN_EPD_CS, LOW);
  digitalWrite(PIN_EPD_DC, HIGH);
  for (uint8_t i = 0; i < 8; i++) {
    digitalWrite(PIN_EPD_SCK, LOW);
    delayMicroseconds(1);
    value = (value << 1) | digitalRead(PIN_EPD_MOSI);
    digitalWrite(PIN_EPD_SCK, HIGH);
    delayMicroseconds(1);
  }
  digitalWrite(PIN_EPD_CS, HIGH);
  pinMode(PIN_EPD_MOSI, OUTPUT);
  return value;
}

static void waitWhileBusy(const char *what) {
  uint32_t start = millis();
  while (digitalRead(PIN_EPD_BUSY) == HIGH) {
    if (millis() - start > BUSY_TIMEOUT_MS) {
      Serial.printf("epd: timed out waiting for %s\n", what);
      return;
    }
    delay(1);
  }
}

